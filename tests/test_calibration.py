@requires_models
def test_brier_improves_after_calibration():
    from src.data import preprocessing as pp
    from src.training.train import load_model
    _, X_test, _, y_test = pp.load_splits()
    raw = load_model("random_forest")
    cal = load_calibrated_model("random_forest_calibrated")
    raw_eval = evaluate_model(raw, X_test, y_test, "raw")
    cal_eval = evaluate_model(cal, X_test, y_test, "cal")
    improvement = ((raw_eval.metrics["brier"] - cal_eval.metrics["brier"])
                   / raw_eval.metrics["brier"])
    assert improvement > 0.05, f"Brier improvement only {improvement:.1%}"


