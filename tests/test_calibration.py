"""
Calibration tests.

Isotonic calibration is a step function, so exact preservation of ROC-AUC
and PR-AUC is NOT expected — ties in calibrated scores slightly reduce
ranking metrics. Tests here use realistic tolerances and explicitly verify
that Brier improves and extreme cases are preserved.

IMPORTANT: the synthetic data generator MUST produce both classes. Single-
class y will make sklearn classifiers return predict_proba with shape
(n, 1), which breaks calibration. See _tiny_data() for the guaranteed-mix
generator.
"""

import numpy as np
import pandas as pd
import pytest

from config import settings
from src.training.calibrate import (
    CalibratedPipeline, calibrate_pipeline, unwrap,
    load_calibrated_model, save_calibrated_model,
)
from src.training.evaluate import evaluate_model
from src.utils.paths import SAVED_MODELS_DIR


def _real_models_present() -> bool:
    return (
        (SAVED_MODELS_DIR / "random_forest.joblib").exists()
        and (SAVED_MODELS_DIR / "random_forest_calibrated.joblib").exists()
    )


requires_models = pytest.mark.skipif(
    not _real_models_present(),
    reason="Models not trained yet. Run: python -m scripts.train_models",
)


def _tiny_data(n: int = 500, seed: int = 0):
    """
    Synthetic dataset with a guaranteed two-class target.

    The label is generated by a deterministic rule based on PAY_0 with mild
    noise, so class balance is stable across seeds (approximately 60/40).
    Explicit assertions at the end guard against regressions in this helper.
    """
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.pipeline import Pipeline
    from src.data.preprocessing import build_preprocessor

    rng = np.random.default_rng(seed)

    # Feature dataframe in canonical order
    X = pd.DataFrame({
        "LIMIT_BAL": rng.normal(100000, 20000, n),
        "AGE": rng.integers(21, 70, n),
        **{f"BILL_AMT{i}": rng.normal(0, 10000, n) for i in range(1, 7)},
        **{f"PAY_AMT{i}": rng.normal(0, 5000, n) for i in range(1, 7)},
        "SEX": rng.integers(1, 3, n),
        "EDUCATION": rng.integers(1, 5, n),
        "MARRIAGE": rng.integers(1, 4, n),
        **{f"PAY_{i}": rng.integers(-2, 10, n) for i in [0, 2, 3, 4, 5, 6]},
    })[list(settings.FEATURE_COLUMNS)]

    # Deterministic signal: customers with PAY_0 > 0 are riskier.
    # logit for PAY_0 <= 0  → ~ -0.7, p ≈ 0.33
    # logit for PAY_0 >  0  → ~ +0.8, p ≈ 0.69
    # With ~75% of rows having PAY_0 > 0, both classes are well represented.
    signal = (X["PAY_0"].values > 0).astype(int)
    noise = rng.normal(0, 0.4, n)
    logit = -0.7 + 1.5 * signal + noise
    p = 1 / (1 + np.exp(-logit))
    y = pd.Series(rng.binomial(1, p, n), name=settings.TARGET_COLUMN)

    # Guard rails — fail fast if this helper ever regresses
    n_pos = int(y.sum())
    n_neg = int(len(y) - n_pos)
    assert y.nunique() == 2, (
        f"Synthetic y has only one class. Class counts: "
        f"{y.value_counts().to_dict()}"
    )
    assert n_pos >= 20, f"Only {n_pos} positives — too few for stable tests."
    assert n_neg >= 20, f"Only {n_neg} negatives — too few for stable tests."

    pipe = Pipeline([
        ("pre", build_preprocessor()),
        ("clf", RandomForestClassifier(n_estimators=20, random_state=0)),
    ])
    pipe.fit(X, y)
    return pipe, X, y


