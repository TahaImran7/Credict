# ---------------------------------------------------------------------------

def test_tiny_data_has_both_classes():
    """Direct guard on the helper itself — fails loudly if y regresses."""
    _, _, y = _tiny_data()
    assert y.nunique() == 2
    assert y.sum() > 20
    assert (y == 0).sum() > 20


def test_calibrated_pipeline_predict_proba_in_range():
    pipe, X, y = _tiny_data()
    cal = calibrate_pipeline(pipe, X, y, n_folds=3)
    probs = cal.predict_proba(X)
    assert probs.shape == (len(X), 2)
    assert np.all((probs >= 0) & (probs <= 1))
    assert np.allclose(probs.sum(axis=1), 1.0, atol=1e-6)


def test_calibrated_pipeline_predict_matches_threshold():
    pipe, X, y = _tiny_data()
    cal = calibrate_pipeline(pipe, X, y, n_folds=3)
    probs = cal.predict_proba(X)[:, 1]
    preds = cal.predict(X)
    expected = (probs >= cal.threshold).astype(int)
    assert np.array_equal(preds, expected)


def test_unwrap_returns_raw_pipeline():
    pipe, X, y = _tiny_data()
    cal = calibrate_pipeline(pipe, X, y, n_folds=3)
    assert unwrap(cal) is pipe
    assert unwrap(pipe) is pipe


def test_save_load_roundtrip(tmp_path, monkeypatch):
    pipe, X, y = _tiny_data()
    cal = calibrate_pipeline(pipe, X, y, n_folds=3)
    monkeypatch.setattr("src.training.calibrate.SAVED_MODELS_DIR", tmp_path)
    save_calibrated_model(cal, "test_cal")
    loaded = load_calibrated_model("test_cal")
    p1 = cal.predict_proba(X)
    p2 = loaded.predict_proba(X)
    assert np.allclose(p1, p2)


def test_single_class_y_raises_clear_error():
    """calibrate_pipeline must fail loudly on single-class input."""
    pipe, X, _ = _tiny_data()
    y_single = pd.Series([0] * len(X), name=settings.TARGET_COLUMN)
    with pytest.raises(ValueError, match="at least 2 classes"):
        calibrate_pipeline(pipe, X, y_single, n_folds=3)


def test_insufficient_class_samples_raises_clear_error():
    """StratifiedKFold needs at least n_folds samples per class."""
    pipe, X, _ = _tiny_data()
    y = pd.Series([0] * (len(X) - 2) + [1, 1], name=settings.TARGET_COLUMN)
    with pytest.raises(ValueError, match="at least n_folds"):
        calibrate_pipeline(pipe, X, y, n_folds=5)


